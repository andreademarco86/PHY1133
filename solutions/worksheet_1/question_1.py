# Get input from user
num1 = float(input("Enter 1st number: "))
num2 = float(input("Enter 2nd number: "))

# Calculate sum, average and sum of squares
total = num1 + num2
average = total / 2.0
sum_of_squares = num1 * num1 + num2 * num2

# Print out result
print(f"Number 1: {num1}, number 2: {num2}")
print(f"Sum: {total}, average: {average}, sum of squares: {sum_of_squares}")

